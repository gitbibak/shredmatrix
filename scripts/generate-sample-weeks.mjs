// Produces src/data/sampleHomeWeeks.js from the real plan engine so the
// public home-workout pages show an actual beginner week instead of marketing
// copy. Run with: npx vite-node scripts/generate-sample-weeks.mjs
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generatePlan, localizePlan } from '../src/data/planGenerator.js';

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const LANGS = ['tr', 'en', 'es'];
const VARIANTS = [
  { key: 'muscle_bodyweight', goal: 'muscle', environment: 'home_bodyweight' },
  { key: 'fat_loss_bodyweight', goal: 'fat_loss', environment: 'home_bodyweight' },
  { key: 'muscle_basic', goal: 'muscle', environment: 'home_basic' },
  { key: 'fat_loss_basic', goal: 'fat_loss', environment: 'home_basic' },
];

const metrics = (goal, environment) => ({
  name: 'Sample', age: 30, gender: 'male', height: 175, weight: 78,
  experience: 'beginner', activityLevel: 'moderate', primaryGoal: goal,
  workSchedule: ['flexible'], budget: 'moderate', trainingEnvironment: environment,
  healthConditions: ['none'], allergies: ['none'],
});

const output = {};
for (const variant of VARIANTS) {
  output[variant.key] = {};
  for (const lang of LANGS) {
    const plan = localizePlan(generatePlan(metrics(variant.goal, variant.environment), 0, lang), lang);
    output[variant.key][lang] = (plan.workoutSplit || []).map((day) => ({
      day: day.day,
      focus: day.focus,
      rest: Boolean(day.isRest) || /dinlen|rest|descanso/i.test(`${day.day} ${day.focus}`),
      exercises: (day.exercises || []).map((exercise) => ({
        name: exercise.name,
        sets: exercise.sets,
        reps: String(exercise.reps),
        rest: String(exercise.rest || ''),
      })),
    }));
  }
}

await writeFile(join(rootDir, 'src/data/sampleHomeWeeks.js'), `// Generated by scripts/generate-sample-weeks.mjs. Do not edit by hand.\nexport const sampleHomeWeeks = ${JSON.stringify(output, null, 2)};\n`);
console.log(`Wrote ${VARIANTS.length} variants x ${LANGS.length} languages.`);
