export function sessionText(lang, key, values = {}) {
  const copy = workoutSessionCopy[lang] || workoutSessionCopy.en;
  return String(copy[key] ?? workoutSessionCopy.en[key] ?? key)
    .replace(/\{(\w+)\}/g, (_, name) => (values[name] ?? ''));
}
